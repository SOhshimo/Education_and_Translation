#######################################################################
# --------------------------------------------------------------------#
#   3.2.1 正規分布
# --------------------------------------------------------------------#
#######################################################################


n <- 100000                                 # 標本サイズ
mu <- 600                                   # 母平均の値
sigma <- 30                                 # 母標準偏差の値
sample <- rnorm(n = n, mean = mu, sd = sigma)     # 乱数を生成
print(sample, dig = 4)                      # 生成した値を表示
hist(sample, col = "grey", breaks = 60, freq = F) # 生成した値を作図

#######################################################################
# --------------------------------------------------------------------#
#   3.2.2 一様分布
# --------------------------------------------------------------------#
#######################################################################

n <- 100000                                 # 標本サイズ
a <- lower.limit <- 0                       # 確率変数の下限
b <- upper.limit <- 10                      # 確率変数の上限
sample <- runif(n = n, min = a, max = b)    # 乱数を生成
print(sample, dig = 4)                      # 生成した値を表示
hist(sample, col = "grey", breaks = 30, freq = F) # 生成した値を作図

#######################################################################
# --------------------------------------------------------------------#
#   3.2.3 二項分布：「コイントス分布」
# --------------------------------------------------------------------#
#######################################################################

n <- 100000                                 # 標本サイズ
N <- 16                                     # コインを投げる個体数
p <- 0.8                                    # 計数（観察）・死亡・雄である確率
sample <- rbinom(n = n, size = N, prob = p) # 乱数を生成
print(sample, dig = 4)                      # 生成した値を表示
plot(table(sample)/n, ylab = '確率', type = 'h', lwd = 20, col = rgb(0, 0, 0, 0.5),
xlim = c(0, 16), lend = 'butt', frame = F)  # 生成した値を作図

#######################################################################
# --------------------------------------------------------------------#
#   3.2.4 ポアソン分布
# --------------------------------------------------------------------#
#######################################################################

n <- 100000                                 # 標本サイズ
lambda <- 5                                 # 観測区画当たりの平均計数（密度または強度）
sample <- rpois(n = n, lambda = lambda)     # 乱数を生成
print(sample, dig = 4)                      # 生成した値を表示
plot(table(sample)/n, ylab = '確率', type = 'h', lwd = 20,col = rgb(0, 0, 0, 0.5),
lend = 'butt', frame = F)                   # 生成した値を作図

